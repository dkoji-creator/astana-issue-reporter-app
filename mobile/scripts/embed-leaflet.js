// Copies Leaflet (JS + CSS) into src/components/leafletAssets.js,
// so the map works without downloading Leaflet from a CDN.
// Run after updating the leaflet package: node scripts/embed-leaflet.js
const fs = require('fs');
const path = require('path');

const dist = path.join(__dirname, '..', 'node_modules', 'leaflet', 'dist');
const js = fs.readFileSync(path.join(dist, 'leaflet.js'), 'utf8');
const css = fs.readFileSync(path.join(dist, 'leaflet.css'), 'utf8');
const out = `// Generated by scripts/embed-leaflet.js from leaflet@${require('leaflet/package.json').version}. Do not edit.
// eslint-disable
export const LEAFLET_JS = ${JSON.stringify(js.replace(/<\/script/gi, '<\\/script'))};
export const LEAFLET_CSS = ${JSON.stringify(css)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'components', 'leafletAssets.js'), out);
console.log('leafletAssets.js written');
